const assert=require('node:assert/strict'),fs=require('node:fs');
const E=require('../../app/src/main/assets/wiredroid/engine.js');
const catalog=new Map(JSON.parse(fs.readFileSync('app/src/main/assets/wiredroid/catalog.json')).map(p=>[p.id,p]));
const scene=JSON.parse(fs.readFileSync('app/src/main/assets/wiredroid/example.json'));
scene.nodes[0].kind='board';scene.nodes[1].kind='resistor';scene.nodes[2].kind='led';
assert.equal(E.validate(scene,catalog),scene);
assert.equal(E.programPin(catalog.get('arduino_Uno_Rev3(fix)'),13),'connector56');
const mode=new Map([['uno:connector56','OUTPUT']]),output=new Map([['uno:connector56',1]]);
let result=E.resolve(scene,catalog,output,mode,new Set());
assert.equal(result.values.get('led:connector1'),1,'signal passes through resistor');
assert.equal(result.values.get('led:connector0'),0,'LED cathode connected to ground');
output.set('uno:connector56',0);
result=E.resolve(scene,catalog,output,mode,new Set());assert.equal(result.values.get('led:connector1'),0);
const short=E.clone(scene);short.wires.push({id:'short',a:{node:'uno',pin:'connector87'},b:{node:'uno',pin:'connector88'}});
assert.equal(E.resolve(short,catalog,new Map(),new Map(),new Set()).conflicts.length,1,'5V-to-ground detected');
const hist=new E.History(scene),changed=E.clone(scene);changed.nodes[0].x=200;hist.push(changed);assert.equal(hist.undo().nodes[0].x,60);assert.equal(hist.redo().nodes[0].x,200);
const bad=E.clone(scene);bad.wires[0].a.pin='missing';assert.throws(()=>E.validate(bad,catalog));
const button={version:1,nodes:[{id:'uno',part:'arduino_Uno_Rev3(fix)',kind:'board',label:'uno',x:0,y:0},{id:'button',part:'Pushbutton',kind:'button',label:'button',x:0,y:0}],wires:[{id:'one',a:{node:'uno',pin:'connector63'},b:{node:'button',pin:'connector0'}},{id:'two',a:{node:'uno',pin:'connector88'},b:{node:'button',pin:'connector1'}}]};
const pullup=new Map([['uno:connector63','INPUT_PULLUP']]);
assert.equal(E.resolve(button,catalog,new Map(),pullup,new Set()).values.get('uno:connector63'),1);
assert.equal(E.resolve(button,catalog,new Map(),pullup,new Set(['button'])).values.get('uno:connector63'),0);
console.log('PASS: validation, pin lookup, resistor propagation, LED polarity, short circuit, history and pull-up button');
